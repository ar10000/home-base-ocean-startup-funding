"""Migrations run on a real Postgres (handbook section 11: upgrade from empty,
downgrade where reversible, and models match migrations)."""

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Column, Engine, Integer, Table, inspect, text

from home_base.core.db import Base

pytestmark = pytest.mark.integration


def _tables(engine: Engine) -> set[str]:
    return set(inspect(engine).get_table_names()) - {"alembic_version"}


def test_database_is_postgres_16(engine: Engine) -> None:
    with engine.connect() as conn:
        version = conn.execute(text("SHOW server_version_num")).scalar_one()
    assert int(version) // 10000 == 16


def test_upgrade_from_empty_then_downgrade_to_empty(alembic_config: Config, engine: Engine) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    assert _tables(engine) == set()
    command.upgrade(alembic_config, "head")


def test_models_match_migrations(alembic_config: Config) -> None:
    """`make db-check`: fails when models.py and the migrations disagree."""
    command.upgrade(alembic_config, "head")
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - the failure message is the point
        pytest.fail(f"Models and migrations disagree; add a migration:\n{exc}")


def test_db_check_fails_for_a_table_with_no_migration(alembic_config: Config) -> None:
    """The guard itself: a model with no migration must make `make db-check` fail."""
    command.upgrade(alembic_config, "head")
    orphan = Table(
        "orphan_without_migration", Base.metadata, Column("id", Integer, primary_key=True)
    )
    try:
        with pytest.raises(AutogenerateDiffsDetected, match="orphan_without_migration"):
            command.check(alembic_config)
    finally:
        Base.metadata.remove(orphan)
